import { useState } from 'react'
import { motion, AnimatePresence } from 'framer-motion'
import { Send, FileSearch, Sparkles, Loader2, BookOpen } from 'lucide-react'

const TABS = ['RAG Demo', 'Agent Workflow', 'AI Concepts']

// Mock RAG response. Swap this for a call to a real FastAPI endpoint
// (e.g. POST /api/query) that runs the actual hybrid-RAG pipeline.
async function mockRagQuery(question) {
  await new Promise((r) => setTimeout(r, 900))
  return {
    chunks: [
      { id: 1, doc: 'architecture-notes.md', snippet: 'Hybrid retrieval merges BM25 and semantic search using Reciprocal Rank Fusion before...' },
      { id: 2, doc: 'evaluation-report.md', snippet: 'Faithfulness is measured by checking whether each generated claim is supported by...' },
      { id: 3, doc: 'ollama-setup.md', snippet: 'Local inference removes the need for an external API call, keeping documents on-device...' },
    ],
    answer:
      `This is a mocked answer for "${question}". In the real system, this would be generated by the local LLM from the retrieved chunks on the left, with every claim traceable to a source.`,
    sources: ['architecture-notes.md', 'evaluation-report.md', 'ollama-setup.md'],
  }
}

function RagDemo() {
  const [question, setQuestion] = useState('How does the reranking stage work?')
  const [loading, setLoading] = useState(false)
  const [result, setResult] = useState(null)

  const run = async (e) => {
    e.preventDefault()
    if (!question.trim()) return
    setLoading(true)
    setResult(null)
    const res = await mockRagQuery(question)
    setResult(res)
    setLoading(false)
  }

  return (
    <div>
      
<form
  onSubmit={run}
  className="flex flex-col min-[451px]:flex-row gap-2"
>
  <input
    value={question}
    onChange={(e) => setQuestion(e.target.value)}
    placeholder="Ask a question about the documents…"
    className="w-full min-w-0 min-[451px]:flex-1 bg-surface-2 border border-border rounded-lg px-4 py-2.5 text-sm text-ink placeholder:text-ink-faint focus:border-retrieval/50 outline-none"
  />

  <button
    type="submit"
    disabled={loading}
    className="btn-primary shrink-0 self-center min-[451px]:self-auto disabled:opacity-60"
  >
    {loading ? (
      <Loader2 size={15} className="animate-spin" />
    ) : (
      <Send size={15} />
    )}
    Ask
  </button>
</form>

      <p className="mt-2 text-xs text-ink-faint">Mocked responses — wire this up to a FastAPI backend to run the real pipeline.</p>

      <AnimatePresence mode="wait">
        {result && (
          <motion.div
            key={result.answer}
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.3 }}
            className="mt-6 grid md:grid-cols-2 gap-4"
          >
            <div className="card-surface bg-surface-2/40 p-4">
              <span className="eyebrow flex items-center gap-1.5"><FileSearch size={12} /> Retrieved chunks</span>
              <div className="mt-3 space-y-2.5">
                {result.chunks.map((c) => (
                  <div key={c.id} className="rounded-lg border border-border bg-surface px-3 py-2.5">
                    <div className="font-mono text-[11px] text-retrieval mb-1">{c.doc}</div>
                    <p className="text-xs text-ink-faint leading-relaxed">{c.snippet}</p>
                  </div>
                ))}
              </div>
            </div>

            <div className="card-surface bg-surface-2/40 p-4">
              <span className="eyebrow flex items-center gap-1.5"><Sparkles size={12} /> Generated answer</span>
              <p className="mt-3 text-sm text-ink-muted leading-relaxed">{result.answer}</p>
              <div className="mt-4 flex flex-wrap gap-1.5">
                {result.sources.map((s) => (
                  <span key={s} className="chip">{s}</span>
                ))}
              </div>
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  )
}

const AGENT_STEPS = [
  { name: 'Search Agent', text: 'Searching the web for recent, relevant sources…' },
  { name: 'Reader Agent', text: 'Extracting and parsing content from the top results…' },
  { name: 'Writer Agent', text: 'Synthesizing findings into a structured report…' },
  { name: 'Critic Agent', text: 'Checking factuality, structure and gaps…' },
  { name: 'Final Report', text: 'Report ready — reviewed and structured.' },
]

function AgentDemo() {
  const [query, setQuery] = useState('Research the latest developments in Multi Agent System?')
  const [running, setRunning] = useState(false)
  const [step, setStep] = useState(-1)

  const run = (e) => {
    e.preventDefault()
    if (!query.trim() || running) return
    setRunning(true)
    setStep(0)
    AGENT_STEPS.forEach((_, i) => setTimeout(() => setStep(i), i * 700))
    setTimeout(() => setRunning(false), AGENT_STEPS.length * 700)
  }

  return (
    <div>
      <form onSubmit={run} className="flex gap-2">
        <input
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          placeholder="Research the latest developments in RAG."
          className="flex-1 bg-surface-2 border border-border rounded-lg px-4 py-2.5 text-sm text-ink placeholder:text-ink-faint focus:border-agent/50 outline-none"
        />
        <button type="submit" disabled={running} className="btn-primary shrink-0 disabled:opacity-60">
          {running ? <Loader2 size={15} className="animate-spin" /> : <Send size={15} />}
          Run
        </button>
      </form>

      <div className="mt-6 space-y-2.5">
        {AGENT_STEPS.map((s, i) => {
          const active = step === i
          const done = step > i
          return (
            <motion.div
              key={s.name}
              animate={{ opacity: step >= i || !running && step === -1 ? 1 : 0.4 }}
              className={`flex items-center gap-3 rounded-lg border px-4 py-3 transition-colors ${
                active ? 'border-agent/50 bg-agent/10' : done ? 'border-border bg-surface-2/40' : 'border-border'
              }`}
            >
              <span className={`h-1.5 w-1.5 rounded-full shrink-0 ${active ? 'bg-agent' : done ? 'bg-ink-faint' : 'bg-border-strong'}`} />
              <div>
                <div className="text-sm font-medium text-ink">{s.name}</div>
                {(active || done) && <div className="text-xs text-ink-faint mt-0.5">{s.text}</div>}
              </div>
            </motion.div>
          )
        })}
      </div>
    </div>
  )
}

